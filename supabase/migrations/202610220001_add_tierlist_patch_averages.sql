-- Tierlist automática y promediada por parche.
-- * Cada snapshot diario guarda su grupo de parche (7.3, 7.3a y 7.3b -> 7.3).
-- * tierlist_patch_averages guarda el promedio acumulado de todos los snapshots del grupo.
-- * tierlist_patch_groups resume cada grupo (selector de la tierlist).
-- * pg_cron llama a la Edge Function update-tierlist todos los días a las 03:30 de España.
--
-- Antes de que el cron funcione hay que crear dos secretos en Vault (una sola vez):
--   select vault.create_secret('https://<project-ref>.supabase.co/functions/v1/update-tierlist', 'tierlist_function_url');
--   select vault.create_secret('<secreto-largo-aleatorio>', 'tierlist_cron_secret');
-- y el mismo secreto en la Edge Function:
--   supabase secrets set TIERLIST_CRON_SECRET=<secreto-largo-aleatorio>

create or replace function public.tierlist_patch_group(p_patch text)
returns text
language sql
immutable
as $$
  select substring(btrim(coalesce(p_patch, '')) from '^(\d+\.\d+)')
$$;

alter table public.tierlist_entries
  add column if not exists patch_group text;
alter table public.tierlist_executions
  add column if not exists patch_group text;

update public.tierlist_entries
set patch_group = public.tierlist_patch_group(patch)
where patch_group is distinct from public.tierlist_patch_group(patch);

update public.tierlist_executions
set patch_group = public.tierlist_patch_group(patch)
where patch_group is distinct from public.tierlist_patch_group(patch);

create index if not exists tierlist_entries_patch_group_idx
  on public.tierlist_entries(patch_group);
create index if not exists tierlist_executions_patch_group_idx
  on public.tierlist_executions(patch_group, snapshot_date desc);

create table if not exists public.tierlist_patch_groups (
  patch_group text primary key,
  latest_patch text not null,
  snapshots_count integer not null default 0,
  first_snapshot_date date,
  last_snapshot_date date,
  elo_penalty_starts_on date,
  updated_at timestamptz not null default now()
);

create table if not exists public.tierlist_patch_averages (
  id bigint generated by default as identity primary key,
  patch_group text not null references public.tierlist_patch_groups(patch_group) on delete cascade,
  champion_key text not null,
  champion_name text not null,
  original_name text,
  external_id text,
  lane text not null,
  tier text not null,
  winrate numeric,
  pickrate numeric,
  banrate numeric,
  difficulty numeric,
  ranking_average numeric not null,
  day_presence_factor numeric not null,
  ranking_final numeric not null,
  position_in_lane integer,
  days_present integer not null,
  days_total integer not null,
  image_url text,
  updated_at timestamptz not null default now(),
  unique (patch_group, lane, champion_key)
);

create index if not exists tierlist_patch_averages_group_idx
  on public.tierlist_patch_averages(patch_group, ranking_final desc);

alter table public.tierlist_patch_groups enable row level security;
alter table public.tierlist_patch_averages enable row level security;

drop policy if exists tierlist_patch_groups_read on public.tierlist_patch_groups;
create policy tierlist_patch_groups_read on public.tierlist_patch_groups
  for select to anon, authenticated using (true);

drop policy if exists tierlist_patch_averages_read on public.tierlist_patch_averages;
create policy tierlist_patch_averages_read on public.tierlist_patch_averages
  for select to anon, authenticated using (true);

grant select on public.tierlist_patch_groups, public.tierlist_patch_averages to anon, authenticated;

create extension if not exists pg_cron;
create extension if not exists pg_net;

-- pg_cron trabaja en UTC: se agenda a las 01:30 y 02:30 UTC y solo dispara la
-- que cae a las 03:30 en Europe/Madrid (cubre horario de verano e invierno).
select cron.schedule(
  'update-tierlist-daily',
  '30 1,2 * * *',
  $job$
    do $task$
    begin
      if extract(hour from now() at time zone 'Europe/Madrid') = 3 then
        perform net.http_post(
          url := (select decrypted_secret from vault.decrypted_secrets where name = 'tierlist_function_url'),
          headers := jsonb_build_object(
            'Content-Type', 'application/json',
            'x-cron-secret', (select decrypted_secret from vault.decrypted_secrets where name = 'tierlist_cron_secret')
          ),
          body := jsonb_build_object('trigger', 'cron'),
          timeout_milliseconds := 150000
        );
      end if;
    end
    $task$;
  $job$
);

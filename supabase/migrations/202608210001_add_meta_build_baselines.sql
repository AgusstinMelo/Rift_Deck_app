create table public.meta_build_baselines (
  id bigint generated by default as identity primary key,
  champion_id text not null,
  role text not null check (role in ('top','jungler','mid','adc','support')),
  patch_version text not null check (btrim(patch_version) <> ''),
  source text not null check (btrim(source) <> ''),
  source_url text,
  source_observed_at timestamptz not null,
  core_item_ids text[] not null default '{}',
  boot_ids text[] not null default '{}',
  keystone_rune_id text,
  primary_rune_ids text[] not null default '{}',
  secondary_rune_id text,
  spell_ids text[] not null default '{}',
  situational jsonb not null default '[]'::jsonb check (jsonb_typeof(situational) = 'array'),
  confidence numeric(4,3) not null default 0.5 check (confidence between 0 and 1),
  source_count integer not null default 1 check (source_count > 0),
  metadata jsonb not null default '{}'::jsonb check (jsonb_typeof(metadata) = 'object'),
  active boolean not null default true,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  unique (champion_id, role, patch_version, source)
);

create index meta_build_baselines_lookup_idx on public.meta_build_baselines (champion_id, role, active, source_observed_at desc);

alter table public.meta_build_baselines enable row level security;

